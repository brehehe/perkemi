    /**
     * Display the Blind Testing Checklist & Feature Analysis Viewer.
     */
    public function checklist(Request $request): Response
    {
        $filePath = base_path('md/ANALISIS_FITUR_DAN_CHECKLIST_PENGUJIAN.md');
        $markdownContent = File::exists($filePath) ? File::get($filePath) : '';

        $activeEvent = Event::find('01a1019a-bd63-7007-9dcd-ac139687e38b')
            ?? Event::latest()->first();

        $categories = $this->checklistCategories();
        $totalItems = collect($categories)->sum(fn ($cat) => count($cat['items'] ?? []));
        $readyItems = collect($categories)->sum(fn ($cat) => collect($cat['items'] ?? [])->where('status', 'ready')->count());
        $partialItems = collect($categories)->sum(fn ($cat) => collect($cat['items'] ?? [])->where('status', 'partial')->count());
        $gapItems = collect($categories)->sum(fn ($cat) => collect($cat['items'] ?? [])->where('status', 'missing')->count());
        $readyPercentage = $totalItems > 0 ? (int) round(($readyItems / $totalItems) * 100) : 100;

        return Inertia::render('Admin/Documentation/Checklist', [
            'markdownContent' => $markdownContent,
            'stats' => [
                'total' => $totalItems,
                'ready' => $readyItems,
                'partial' => $partialItems,
                'gap' => $gapItems,
                'readyPercentage' => $readyPercentage,
                'coreReadyPercentage' => 100,
            ],
            'phases' => $this->phases(),
            'categories' => $categories,
            'recentChanges' => $this->recentChanges(),
            'sampleEvent' => $activeEvent ? [
                'id' => $activeEvent->id,
                'slug' => $activeEvent->slug,
                'name' => $activeEvent->name,
            ] : [
                'id' => '01a1019a-bd63-7007-9dcd-ac139687e38b',
                'slug' => 'popda-xv-jawa-timur-2026',
                'name' => 'POPDA XV Provinsi Jawa Timur 2026 — Shorinji Kempo',
            ],
        ]);
    }

    /**
     * Download the raw markdown documentation file.
     */
    public function download(): HttpResponse
    {
        $filePath = base_path('md/ANALISIS_FITUR_DAN_CHECKLIST_PENGUJIAN.md');

        abort_unless(File::exists($filePath), 404, 'File dokumentasi belum ditemukan.');

        $content = File::get($filePath);

        return response($content, 200, [
            'Content-Type' => 'text/markdown; charset=UTF-8',
            'Content-Disposition' => 'attachment; filename="ANALISIS_FITUR_DAN_CHECKLIST_PENGUJIAN.md"',
        ]);
    }

